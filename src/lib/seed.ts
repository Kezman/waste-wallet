export function seedRequests(now: number): MoneyRequest[] {
  return SEED.map((seed, index) => {
    const createdAt = now - seed.hoursAgo * HOUR
    const closesAt = createdAt + (seed.windowHours ?? 48) * HOUR
    const id = `req-${index + 1}`

    return {
      id,
      code: `З-${String(index + 1).padStart(4, '0')}`,
      title: seed.title,
      price: seed.price,
      category: seed.category,
      reason: seed.reason,
      alternative: seed.alternative,
      author: seed.author,
      authorKarma: seed.karma,
      createdAt: new Date(createdAt).toISOString(),
      closesAt: new Date(closesAt).toISOString(),
      status: seed.status ?? 'open',
      outcome: seed.outcome,
      mine: seed.author === CURRENT_USER.name,
      votes: seed.votes.map((vote, voteIndex) => ({
        id: `${id}-v${voteIndex + 1}`,
        author: vote.author,
        karma: vote.karma,
        decision: vote.decision,
        text: vote.text,
        createdAt: new Date(now - vote.hoursAgo * HOUR).toISOString(),
      })),
    }
  })
}
